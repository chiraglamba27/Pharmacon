create or replace function public.set_current_version(target_id text)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if not public.is_admin() then
    raise exception 'insufficient permissions';
  end if;
  update public.versions set status = 'archived' where status = 'current' and id <> target_id;
  update public.versions set status = 'current' where id = target_id;
end;
$$;

create or replace function public.confirm_sample_prescription()
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  existing_id text;
  actor_name text;
  actor_role text;
begin
  if public.current_role() not in ('admin','instructor','doctor','clinic-staff') then
    raise exception 'insufficient permissions';
  end if;

  select id into existing_id from public.prescriptions where id = 'RX-DEMO-CONFIRMED';
  if existing_id is not null then
    return jsonb_build_object('prescriptionId', existing_id, 'alreadyConfirmed', true);
  end if;

  select name, role into actor_name, actor_role from public.profiles where id = auth.uid();

  insert into public.prescriptions (id, patient_id, patient_name, doctor_name, status)
  values ('RX-DEMO-CONFIRMED', 'PT-1001', 'Rahul Kumar', 'Dr. A. Sharma', 'confirmed');

  insert into public.prescription_fields (prescription_id, label, value, confidence, needs_verification) values
    ('RX-DEMO-CONFIRMED','Medicine','Amoxicillin',94,0),
    ('RX-DEMO-CONFIRMED','Strength','500 mg',97,0),
    ('RX-DEMO-CONFIRMED','Dosage Form','Tablet',96,0),
    ('RX-DEMO-CONFIRMED','Frequency','1-0-1',86,1),
    ('RX-DEMO-CONFIRMED','Route','Oral',92,0),
    ('RX-DEMO-CONFIRMED','Duration','5 days',91,0),
    ('RX-DEMO-CONFIRMED','Instructions','After food',88,1);

  update public.inventory_items
  set stock = greatest(stock - 1, 0), updated_at = timezone('utc', now())
  where id = 'INV-001';

  insert into public.audit_events (id, actor, role, action, entity, entity_id, status, details)
  values
    ('AE-' || substr(gen_random_uuid()::text, 1, 8), coalesce(actor_name, 'Staff User'), coalesce(actor_role, 'clinic-staff'), 'Prescription confirmed', 'Prescription', 'RX-DEMO-CONFIRMED', 'success', ''),
    ('AE-' || substr(gen_random_uuid()::text, 1, 8), 'System', 'System', 'Inventory adjusted', 'Inventory', 'INV-001', 'success', '');

  return jsonb_build_object('prescriptionId', 'RX-DEMO-CONFIRMED', 'alreadyConfirmed', false);
end;
$$;

grant execute on function public.set_current_version(text) to authenticated;
