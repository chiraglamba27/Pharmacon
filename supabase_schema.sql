-- --------------------------------------------------------------------------
-- Profiles / authentication metadata
-- Supabase Auth owns credentials in auth.users. This table stores app roles.
-- Demo accounts can be created by deploying/invoking supabase/functions/bootstrap-demo-users.
-- --------------------------------------------------------------------------
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text unique not null,
  name text not null,
  role text not null check (role in ('doctor','clinic-staff','pharmacist','patient','admin','instructor')),
  created_at timestamptz not null default timezone('utc', now())
);

create or replace function public.current_role()
returns text
language sql
stable
security definer
set search_path = public
as $$
  select role from public.profiles where id = auth.uid();
$$;

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select coalesce(public.current_role() in ('admin','instructor'), false);
$$;

